# Compiles the built-in shaders to SPIR-V and writes them as C arrays (linux/vk/vk_builtin_spv.h).
import os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__)); out = sys.argv[1]
def spv(src, stage, defs):
    with tempfile.TemporaryDirectory() as d:
        o = os.path.join(d, "o.spv")
        subprocess.check_call(["glslangValidator", "-V", "--target-env", "vulkan1.3", "-S", stage, "-I" + here, *["-D" + k for k in defs], "-o", o, src], stdout=subprocess.DEVNULL)
        return open(o, "rb").read()
def arr(name, data):
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    body = ",".join("0x%08x" % w for w in words)
    return "static const uint32_t %s[] = {%s};\n" % (name, body)
text = "/* generated by linux/vk/builtin/gen.py */\n#pragma once\n#include <stdint.h>\n"
text += arr("spv_clear_vs", spv(os.path.join(here, "clear.vert"), "vert", []))
names = []
for t, ty in enumerate(["vec4", "uvec4", "ivec4"]):
    for loc in range(8):
        n = "spv_clear_fs_%d_%d" % (t, loc); names.append(n)
        text += arr(n, spv(os.path.join(here, "clear.frag"), "frag", ["LOC=%d" % loc, "TYPE=" + ty]))
text += "static const uint32_t *const spv_clear_fs[3][8] = {%s};\n" % ",".join("{" + ",".join(names[t * 8:t * 8 + 8]) + "}" for t in range(3))
text += "static const size_t spv_clear_fs_size[3][8] = {%s};\n" % ",".join("{" + ",".join("sizeof %s" % n for n in names[t * 8:t * 8 + 8]) + "}" for t in range(3))
# FSR 1 at the present (vk_fsr.c), with AMD's headers (builtin/ffx): EASU and RCAS, full-screen draws
text += arr("spv_fsr_easu", spv(os.path.join(here, "fsr_easu.frag"), "frag", []))
text += arr("spv_fsr_easu_h", spv(os.path.join(here, "fsr_easu.frag"), "frag", ["HALF=1"]))
text += arr("spv_fsr_vs", spv(os.path.join(here, "fsr.vert"), "vert", []))
text += arr("spv_fsr_rcas", spv(os.path.join(here, "fsr_rcas.frag"), "frag", []))
text += arr("spv_fsr_rcas_h", spv(os.path.join(here, "fsr_rcas.frag"), "frag", ["HALF=1"]))
# Snapdragon GSR 1 at the present (vk_fsr.c), Qualcomm's shader (builtin/sgsr)
text += arr("spv_sgsr", spv(os.path.join(here, "sgsr1.frag"), "frag", []))
open(out, "w").write(text)
